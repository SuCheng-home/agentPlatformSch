function pad(n) {
  return String(n).padStart(3, '0');
}

const STEPS_AGENT = ['点击「进入使用」打开智能体对话', '按提示输入课题、年级等关键信息', '根据输出结果继续追问或要求调整', '复制结果到教学设计或课件中使用'];
const STEPS_TOOL = ['点击「打开工具」进入工具页面', '上传或输入素材', '预览生成结果并下载使用'];

export function buildSeedResources() {
  const list = [];
  let id = 1;
  const counters = {};
  const nextCode = (prefix) => {
    counters[prefix] = (counters[prefix] || 0) + 1;
    return `${prefix}-${pad(counters[prefix])}`;
  };

  subjectAgents.forEach(([subject, scene, name, desc, grades, author, prompt]) => {
    list.push({
      id: `r${id++}`, type: 'agent', matrix: 'subject', subject, scene, grades, name, desc, author,
      dept: '学科组', prompt, steps: STEPS_AGENT, url: '#', status: 'published',
      code: nextCode(`XK-${subjectLabel[subject]}`), order: id, featured: id % 4 === 0
    });
  });
  subjectTools.forEach(([subject, scene, name, desc, dept]) => {
    list.push({
      id: `r${id++}`, type: 'tool', matrix: 'subject', subject, scene, grades: ['七年级', '八年级', '九年级'], name, desc,
      author: dept, dept, steps: STEPS_TOOL, url: '#', status: 'published',
      code: nextCode(`XK-${subjectLabel[subject]}`), order: id, featured: false
    });
  });
  educationAgents.forEach(([domain, name, desc, author, prompt]) => {
    list.push({
      id: `r${id++}`, type: 'agent', matrix: 'education', domain, name, desc, author, dept: '德育与行政',
      prompt, steps: STEPS_AGENT, url: '#', status: 'published',
      code: nextCode(`YR-${domainLabel[domain]}`), order: id, featured: id % 3 === 0
    });
  });
  educationTools.forEach(([domain, name, desc, dept]) => {
    list.push({
      id: `r${id++}`, type: 'tool', matrix: 'education', domain, name, desc, author: dept, dept,
      steps: STEPS_TOOL, url: '#', status: 'published',
      code: nextCode(`YR-${domainLabel[domain]}`), order: id, featured: false
    });
  });
  standalonePrompts.forEach(([category, name, prompt, author]) => {
    list.push({
      id: `r${id++}`, type: 'prompt', matrix: 'prompt', category, name, desc: prompt.split('\n')[0].slice(0, 46),
      prompt, author, dept: '教师共建', status: 'published', code: nextCode('TS'), order: id, featured: false
    });
  });
  return list;
}

